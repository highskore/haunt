"""Writes macos/Sources/Tokens.swift from design/tokens.json so Swift never hard-codes a design value."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "design/tokens.json"
OUT = ROOT / "macos/Sources/Tokens.swift"


def ident(parts):
    words = [w for p in parts for w in re.split(r"[_\-]", p) if w]
    return words[0] + "".join(w[:1].upper() + w[1:] for w in words[1:])


def swift_value(kind, v):
    if kind == "color":
        h = v.lstrip("#")
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        return "NSColor", f"NSColor(srgbRed: {r}.0 / 255, green: {g}.0 / 255, blue: {b}.0 / 255, alpha: 1)"
    if isinstance(v, bool):
        return "Bool", "true" if v else "false"
    if isinstance(v, (int, float)):
        return "CGFloat", repr(v)
    if isinstance(v, list) and all(isinstance(x, (int, float)) for x in v):
        return "[CGFloat]", "[" + ", ".join(repr(x) for x in v) + "]"
    if isinstance(v, list):
        return "[String]", "[" + ", ".join(json.dumps(x) for x in v) + "]"
    return "String", json.dumps(v)


def main():
    tokens = json.loads(SRC.read_text())["tokens"]
    groups = {}
    for key in sorted(tokens):
        kind, *rest = key.split(".")
        groups.setdefault(kind, []).append((key, ident(rest), tokens[key]["value"]))
    lines = ["// Generated by macos/gen-tokens.sh from design/tokens.json. Do not edit.", "import AppKit", "", "enum Tok {"]
    for kind in sorted(groups):
        lines.append(f"    enum {kind.capitalize()} {{")
        for key, name, value in groups[kind]:
            typ, expr = swift_value(kind, value)
            lines.append(f"        /// {key}")
            lines.append(f"        static let {name}: {typ} = {expr}")
        lines.append("    }")
    lines.append("}")
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else f"{OUT} is stale; run macos/gen-tokens.sh")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(tokens)} tokens)")


if __name__ == "__main__":
    main()

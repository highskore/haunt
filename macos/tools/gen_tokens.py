"""Writes macos/Sources/Tokens.swift from design/tokens.json so Swift never hard-codes a design value.

The tokens become `Theme`'s defaults (the black-and-white look), `Tok.*` reads them through `Theme.current`,
and `Theme.keys` maps each tokens.json name to its field so a theme file can override it."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "design/tokens.json"
OUT = ROOT / "macos/Sources/Tokens.swift"

# Swift type of a value -> the `Theme.Key` case that sets it.
KEY_CASE = {"NSColor": "color", "CGFloat": "number", "[CGFloat]": "numbers", "String": "string", "[String]": "strings"}


def ident(parts):
    words = [w for p in parts for w in re.split(r"[_\-]", p) if w]
    return words[0] + "".join(w[:1].upper() + w[1:] for w in words[1:])


def swift_value(kind, v):
    if kind == "color":
        h = v.lstrip("#")
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        return "NSColor", f"NSColor(srgbRed: {r}.0 / 255, green: {g}.0 / 255, blue: {b}.0 / 255, alpha: 1)"
    if isinstance(v, bool):
        return "Bool", "true" if v else "false"
    if isinstance(v, (int, float)):
        return "CGFloat", repr(v)
    if isinstance(v, list) and all(isinstance(x, (int, float)) for x in v):
        return "[CGFloat]", "[" + ", ".join(repr(x) for x in v) + "]"
    if isinstance(v, list):
        return "[String]", "[" + ", ".join(json.dumps(x) for x in v) + "]"
    return "String", json.dumps(v)


def main():
    tokens = json.loads(SRC.read_text())["tokens"]
    groups = {}
    for key in sorted(tokens):
        kind, *rest = key.split(".")
        typ, expr = swift_value(kind, tokens[key]["value"])
        groups.setdefault(kind, []).append((key, ident(rest), typ, expr))

    lines = ["// Generated by macos/gen-tokens.sh from design/tokens.json. Do not edit.", "import AppKit", ""]
    lines += ["/// Every token, defaulting to the black-and-white look; a theme overrides some of them.",
              "struct Theme: Equatable {"]
    for kind in sorted(groups):
        lines.append(f"    var {kind} = {kind.capitalize()}s()")
    lines.append("    var app = AppTokens()")
    lines.append("    var effects = Effects()")
    for kind in sorted(groups):
        lines += ["", f"    struct {kind.capitalize()}s: Equatable {{"]
        for key, name, typ, expr in groups[kind]:
            lines.append(f"        var {name}: {typ} = {expr}")
        lines.append("    }")
    lines += ["", "    /// Each token by its tokens.json name.", "    static let keys: [String: Key] = ["]
    for kind in sorted(groups):
        for key, name, typ, _ in groups[kind]:
            lines.append(f"        \"{key}\": .{KEY_CASE[typ]}(\\.{kind}.{name}),")
    lines += ["    ]", "}", "", "/// The current theme's tokens, by the names Swift code uses.", "enum Tok {"]
    for kind in sorted(groups):
        lines.append(f"    enum {kind.capitalize()} {{")
        for key, name, typ, _ in groups[kind]:
            lines.append(f"        /// {key}")
            lines.append(f"        static var {name}: {typ} {{ Theme.current.{kind}.{name} }}")
        lines.append("    }")
    lines.append("}")
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else f"{OUT} is stale; run macos/gen-tokens.sh")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(tokens)} tokens)")


if __name__ == "__main__":
    main()
